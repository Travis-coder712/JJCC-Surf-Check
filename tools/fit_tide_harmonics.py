#!/usr/bin/env python3
"""Fit harmonic constituents to BOM Point Lonsdale highs/lows (data/tides.json).

The app uses the BOM events directly while they last; these harmonics are only the fallback
after the file runs out. Constraints: h(t_i) = height_i and h'(t_i) = 0 at each extreme.
Prints held-out accuracy and the JS constants to paste into engine/tides.js.
"""
import json, numpy as np

# speeds in degrees/hour
SPEEDS = {'M2': 28.9841042, 'S2': 30.0, 'N2': 28.4397295, 'K2': 30.0821373, 'K1': 15.0410686,
          'O1': 13.9430356, 'P1': 14.9589314, 'Q1': 13.3986609, '2N2': 27.8953548, 'NU2': 28.5125831,
          'MU2': 27.9682084, 'L2': 29.5284789, 'T2': 29.9589333, 'J1': 15.5854433, 'OO1': 16.1391017,
          'M4': 57.9682084, 'MS4': 58.9841042, 'MN4': 57.4238337, 'M6': 86.9523127, 'SA': 0.0410686,
          'SSA': 0.0821373, 'MM': 0.5443747, 'MF': 1.0980331}
EPOCH = 1767225600  # 2026-01-01T00:00Z


def design(t_hours, deriv=False):
    cols = [np.zeros_like(t_hours) if deriv else np.ones_like(t_hours)]
    for s in SPEEDS.values():
        w = np.radians(s)
        if deriv:
            cols += [-w * np.sin(w * t_hours), w * np.cos(w * t_hours)]
        else:
            cols += [np.cos(w * t_hours), np.sin(w * t_hours)]
    return np.column_stack(cols)


def fit(ev):
    t = (ev[:, 0] - EPOCH) / 3600.0
    A = np.vstack([design(t), design(t, True) * 3.0])  # weight slope constraint (m/h)
    y = np.concatenate([ev[:, 2], np.zeros(len(t))])
    return np.linalg.lstsq(A, y, rcond=None)[0]


def predict(coef, t_hours):
    with np.errstate(all="ignore"):  # numpy 2 + Accelerate emits spurious matmul warnings
        return design(t_hours) @ coef


def extremes(coef, t0, t1):
    t = np.arange(t0, t1, 1 / 60.0)
    h = predict(coef, t)
    i = np.where((np.diff(np.sign(np.diff(h)))) != 0)[0] + 1
    return t[i], h[i], np.diff(h)[i - 1] > 0


def main():
    d = json.load(open('data/tides.json'))
    ev = np.array(d['events'], dtype=float)
    split = EPOCH + 365 * 86400
    train, test = ev[ev[:, 0] < split], ev[ev[:, 0] >= split]
    coef = fit(train)
    tt = (test[:, 0] - EPOCH) / 3600.0
    pt, ph, _ = extremes(coef, tt[0] - 6, tt[-1] + 6)
    dt, dh = [], []
    for t, h in zip(tt, test[:, 2]):
        j = np.argmin(abs(pt - t)); dt.append((pt[j] - t) * 60); dh.append(ph[j] - h)
    dt, dh = np.abs(dt), np.abs(dh)
    print(f'held-out 2027: time err median {np.median(dt):.0f} min, p90 {np.percentile(dt,90):.0f} min; '
          f'height err median {np.median(dh):.2f} m, p90 {np.percentile(dh,90):.2f} m')
    coef = fit(ev)  # refit on everything for shipping
    print('// generated by tools/fit_tide_harmonics.py from', d['station'])
    print(f'const HARMONIC_EPOCH = {EPOCH};')
    print(f'const Z0 = {coef[0]:.4f};')
    print('const CONSTITUENTS = [')
    for k, (name, s) in enumerate(SPEEDS.items()):
        a, b = coef[1 + 2 * k], coef[2 + 2 * k]
        print(f"  ['{name}', {s}, {a:.4f}, {b:.4f}],")
    print('];')


if __name__ == '__main__':
    main()
