// ===================================================================
// Tides — BOM Point Lonsdale predictions (data/tides.json).
//
// Point Lonsdale is BOM's nearest official open-coast port (~30 km east
// of Torquay). Tide modelling shows no measurable time offset between
// Lonsdale and Torquay/Anglesea/Lorne at 15-minute resolution, so the
// times are used as-is.
//
// Between published highs/lows the curve is cosine-interpolated (the
// standard method for tide tables). After the file runs out, a
// 23-constituent harmonic fit to the same BOM data takes over
// (held-out accuracy: median 4 min, 2 cm). Refresh yearly with
// tools/fetch_bom_tides.py.
// ===================================================================
(function (root) {
  'use strict';

  // generated by tools/fit_tide_harmonics.py from Point Lonsdale, VIC (BOM VIC_TP009)
  const HARMONIC_EPOCH = 1767225600;
  const Z0 = 1.0229;
  const CONSTITUENTS = [
    ['M2', 28.9841042, 0.3911, -0.2014],
    ['S2', 30.0, -0.1156, 0.0385],
    ['N2', 28.4397295, 0.0368, -0.0732],
    ['K2', 30.0821373, 0.0241, -0.0254],
    ['K1', 15.0410686, -0.0012, -0.1460],
    ['O1', 13.9430356, -0.0911, -0.0605],
    ['P1', 14.9589314, 0.0136, -0.0394],
    ['Q1', 13.3986609, -0.0274, -0.0069],
    ['2N2', 27.8953548, -0.0021, -0.0093],
    ['NU2', 28.5125831, -0.0138, -0.0116],
    ['MU2', 27.9682084, -0.0211, -0.0104],
    ['L2', 29.5284789, -0.0238, 0.0106],
    ['T2', 29.9589333, -0.0095, 0.0033],
    ['J1', 15.5854433, 0.0013, -0.0038],
    ['OO1', 16.1391017, -0.0107, 0.0023],
    ['M4', 57.9682084, 0.0278, 0.0076],
    ['MS4', 58.9841042, -0.0005, -0.0014],
    ['MN4', 57.4238337, 0.0104, -0.0027],
    ['M6', 86.9523127, -0.0045, 0.0060],
    ['SA', 0.0410686, -0.0575, 0.0055],
    ['SSA', 0.0821373, 0.0201, -0.0171],
    ['MM', 0.5443747, 0.0024, -0.0057],
    ['MF', 1.0980331, 0.0120, 0.0007],
  ];

  let events = []; // [{t: ms, high: bool, h: m}]
  let meta = null;

  function load(doc) {
    meta = doc;
    events = doc.events.map(([t, hi, h]) => ({ t: t * 1000, high: hi === 1, h }));
  }

  function harmonicHeight(tMs) {
    const hrs = (tMs / 1000 - HARMONIC_EPOCH) / 3600;
    let h = Z0;
    for (const [, speed, a, b] of CONSTITUENTS) {
      const w = speed * Math.PI / 180;
      h += a * Math.cos(w * hrs) + b * Math.sin(w * hrs);
    }
    return h;
  }

  // Extremes from the harmonic model, for dates past the BOM file.
  function harmonicExtremes(t0, t1) {
    const out = [];
    const step = 5 * 60000;
    let prev = harmonicHeight(t0 - step), cur = harmonicHeight(t0);
    for (let t = t0; t <= t1; t += step) {
      const next = harmonicHeight(t + step);
      if (cur > prev && cur >= next) out.push({ t, high: true, h: cur });
      else if (cur < prev && cur <= next) out.push({ t, high: false, h: cur });
      prev = cur; cur = next;
    }
    return out;
  }

  function inBomRange(tMs) {
    return events.length > 1 && tMs >= events[0].t && tMs <= events[events.length - 1].t;
  }

  // Index of the last event at or before tMs (binary search).
  function indexBefore(tMs) {
    let lo = 0, hi = events.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (events[mid].t <= tMs) lo = mid; else hi = mid - 1;
    }
    return lo;
  }

  function bracket(tMs) {
    if (inBomRange(tMs)) {
      const i = indexBefore(tMs);
      return [events[i], events[Math.min(i + 1, events.length - 1)], 'bom'];
    }
    const ex = harmonicExtremes(tMs - 8 * 3600000, tMs + 8 * 3600000);
    const after = ex.findIndex(e => e.t > tMs);
    return [ex[Math.max(0, after - 1)], ex[after], 'harmonic'];
  }

  function cosInterp(a, b, tMs) {
    if (b.t === a.t) return a.h;
    const x = (tMs - a.t) / (b.t - a.t);
    return a.h + (b.h - a.h) * (1 - Math.cos(Math.PI * x)) / 2;
  }

  const STAGES = ['low', 'low-mid', 'mid', 'mid-high', 'high'];

  // Full tide state at a moment. `fraction` is how far between this
  // tide's low (0) and high (1) — independent of the day's inequality.
  function at(tMs) {
    const [prev, next, source] = bracket(tMs);
    const h = cosInterp(prev, next, tMs);
    const lowH = prev.high ? next.h : prev.h;
    const highH = prev.high ? prev.h : next.h;
    const fraction = Math.max(0, Math.min(1, (h - lowH) / Math.max(0.05, highH - lowH)));
    const rising = !prev.high;
    const stage = STAGES[Math.min(4, Math.floor(fraction * 5))];
    return { h, fraction, rising, stage, prev, next, source };
  }

  function extremesBetween(t0, t1) {
    if (inBomRange(t0) && inBomRange(t1)) return events.filter(e => e.t >= t0 && e.t <= t1);
    return harmonicExtremes(t0, t1);
  }

  function describe(state) {
    const dir = state.rising ? 'rising' : 'falling';
    return `${state.stage} & ${dir}`;
  }

  root.SurfTides = {
    load, at, extremesBetween, describe, harmonicHeight,
    get meta() { return meta; },
    get validUntil() { return events.length ? events[events.length - 1].t : 0; },
  };
})(typeof window !== 'undefined' ? window : globalThis);
